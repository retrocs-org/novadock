#!/usr/bin/env python3
"""Generate HASS status artwork using the dock's shared pixel palette."""
from pathlib import Path
import argparse
from generate_collection_icons import Canvas, png, ilbm
from artifact_compare import same_artifact
ROOT=Path(__file__).resolve().parents[1]
def artwork(sad=False):
    c=Canvas();b=c.box;l=c.line
    l(2,13,16,2,1);l(16,2,30,13,1)
    l(3,13,16,3,3);l(16,3,29,13,3)
    b(6,12,21,14,1);b(8,13,17,11,2);b(8,13,17,1,3)
    b(10,16,3,3,1);b(20,16,3,3,1)
    b(11,16,1,1,3);b(21,16,1,1,3)
    if sad:
        b(14,20,5,1,1);b(12,21,2,2,1);b(19,21,2,2,1)
        l(4,28,11,28,4);l(20,28,28,28,4)
        l(13,27,15,29,7);l(17,27,19,29,7)
    else:
        b(14,22,5,1,1);b(12,20,2,2,1);b(19,20,2,2,1)
        l(4,28,28,28,4)
    b(2,26,4,5,2);b(3,26,2,1,3);b(26,26,4,5,2);b(27,26,2,1,3)
    return c.p

def rectangles(pixels):
    runs=[]
    for y,row in enumerate(pixels):
        x=0
        while x<32:
            color=row[x];end=x+1
            while end<32 and row[end]==color:end+=1
            if color:runs.append((x,y,end-x,1,color))
            x=end
    return runs

def generated_header():
    rows=','.join('{'+','.join(map(str,r))+'}' for r in rectangles(artwork(True)))
    return ('/* Generated by tools/generate_hass_icons.py. */\n'
            '#ifndef ND_HASS_SAD_ART_H\n#define ND_HASS_SAD_ART_H\n'
            'struct NDHassSadRect {unsigned char x,y,w,h,color;};\n'
            'static const struct NDHassSadRect nd_hass_sad_rects[]={\n'+rows+'\n};\n'
            '#define ND_HASS_SAD_RECT_COUNT (sizeof(nd_hass_sad_rects)/sizeof(nd_hass_sad_rects[0]))\n'
            '#endif\n')

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    files={ROOT/'plugin_src/hass/artwork/nd_hass_sad_art.h':generated_header().encode()}
    for name,sad in [('HASS',False),('SadHASS',True)]:
        pixels=artwork(sad);files[ROOT/'plugin_src/hass/artwork'/f'{name}.png']=png(pixels);files[ROOT/'plugin_src/hass/artwork'/f'{name}.iff']=ilbm(pixels)
    for path,data in files.items():
        if args.check:assert same_artifact(path.read_bytes(),data), str(path)+' requires regeneration'
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print('HASS connected/sad PNG, ILBM and theme-aware runtime artwork are current.')
if __name__=='__main__':main()
