#!/usr/bin/env python3
"""Generate compact scanline artwork for the native Boing Ball screen saver."""
from pathlib import Path
import math
SIZE=40
FRAMES=16

def frame(number):
    spans=[]
    tilt=math.radians(20)
    for y in range(SIZE):
        row=[]
        for x in range(SIZE):
            sx=(x+.5-SIZE/2)/(SIZE/2);sy=(y+.5-SIZE/2)/(SIZE/2)
            distance=sx*sx+sy*sy
            if distance>=1:row.append(0);continue
            z=math.sqrt(1-distance)
            tx=sx*math.cos(tilt)+sy*math.sin(tilt)
            ty=sy*math.cos(tilt)-sx*math.sin(tilt)
            longitude=math.atan2(tx,z)+number*math.pi/(2*FRAMES)
            latitude=math.asin(ty)
            red=(math.floor(longitude*4/math.pi)+math.floor((latitude+math.pi/2)*6/math.pi))&1
            light=max(0,(-sx*.35-sy*.45+z*.82))
            row.append((8 if light>.78 else 9 if light>.35 else 10) if red else (2 if light>.78 else 11 if light>.35 else 12))
        x=0
        while x<SIZE:
            end=x+1
            while end<SIZE and row[end]==row[x]:end+=1
            if row[x]:spans.extend((x,y,end-x,row[x]))
            x=end
    return spans

def generate():
    data=[];offsets=[0]
    for i in range(FRAMES):data.extend(frame(i));offsets.append(len(data))
    lines=['/* Generated by tools/generate_boing_art.py; native scanline runs. */',
           '#ifndef ND_BOING_ART_H','#define ND_BOING_ART_H',
           '#define ND_BOING_FRAMES 16','#define ND_BOING_SIZE 40',
           'static const unsigned short nd_boing_offsets[17]={'+','.join(map(str,offsets))+'};',
           'static const unsigned char nd_boing_runs[]={']
    for start in range(0,len(data),32):lines.append(' '+','.join(map(str,data[start:start+32]))+',')
    lines.extend(['};','#endif',''])
    return '\n'.join(lines)

if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'include/nd_boing_art.h';text=generate()
    if args.check:
        if not path.is_file() or path.read_text()!=text:raise SystemExit('Regenerate Boing Ball artwork.')
    else:path.write_text(text)
