#!/usr/bin/env python3
"""Extract NovaDock's translatable messages from the dock's sources
(src/novadock.c and src/dock_*.c).

Writes catalogs/novadock.cd (catalog descriptor for CatComp/FlexCat) and
include/nd_strings.h (English text -> catalog ID).  Run after changing any
user-visible dock message; tests/run_host_tests.sh checks both are current.
  python3 tools/generate_catalog.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT / 'src' / 'novadock.c'] + sorted((ROOT / 'src').glob('dock_*.c'))
LIT = re.compile(r'"((?:[^"\\]|\\.)*)"')
SINKS = ('show_feedback(', 'report_problem(', 'ask_user(', 'nd_tr(', 'nd_trf(')
ARRAYS = ('folder_sort_labels', 'task_actions', 'task_actions_nopin', 'launcher_actions', 'drawer_actions', 'media_actions', 'plugin_actions',
          'eyes_actions', 'clock_actions', 'dopus_actions', 'spacer_actions',
          'dock_actions', 'months', 'week')

# Newly introduced strings whose Swedish translation is known.  The .ct file
# is ISO-8859-1, so keeping these defaults here also lets the generator update
# it safely without depending on a UTF-8 editor.
SV_DEFAULTS = {
    'Add item...': 'Nytt objekt...',
}


def call_body(text, start):
    depth, i = 0, start
    in_str = False
    while i < len(text):
        c = text[i]
        if in_str:
            if c == '\\':
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
        i += 1
    return ''


def literals(body):
    """String literals with adjacent-literal concatenation applied."""
    out, last_end, current = [], None, None
    for m in LIT.finditer(body):
        gap = body[last_end:m.start()] if last_end is not None else None
        if current is not None and gap is not None and gap.strip() == '':
            current += m.group(1)
        else:
            if current is not None:
                out.append(current)
            current = m.group(1)
        last_end = m.end()
    if current is not None:
        out.append(current)
    return out


def collect():
    text = '\n'.join(path.read_text() for path in SOURCES)
    found = []
    for sink in SINKS:
        pos = 0
        while True:
            i = text.find(sink, pos)
            if i < 0:
                break
            body = call_body(text, i + len(sink) - 1)
            found.extend(s for s in literals(body) if re.search('[A-Za-z]{2}', s))
            pos = i + 1
    # Every menu/label table is translatable, including ones added later.
    names = list(ARRAYS) + [n for n in re.findall(
        r'static const char \*(\w+_(?:actions|nopin|labels))\s*\[', text)
        if n not in ARRAYS]
    for name in names:
        m = re.search(r'\b' + name + r'\s*\[[^\]]*\]\s*=\s*\{(.*?)\};', text, re.S)
        if m:
            found.extend(literals(m.group(1)))
    # The definition (static or shared between the dock's files), not a
    # prototype.
    m = re.search(r'^(?:static )?const char \*popup_label_en\([^;{]*?\{.*?\n\}',
                  text, re.S | re.M)
    if m:
        found.extend(s for s in literals(m.group(0)) if re.search('[a-z]', s))
    seen, ordered = set(), []
    for s in found:
        # Identifiers such as "READY" are protocol values, not messages.
        if s != 'OK' and not re.search('[a-z]', s):
            continue
        if s not in seen:
            seen.add(s)
            ordered.append(s)
    return ordered


def main():
    strings = collect()
    cd = ['; NovaDock catalog descriptor - generated by tools/generate_catalog.py',
          '; Translate with FlexCat or CatComp; keep printf conversions (%s, %d)',
          '; in the same order and the translation within 80 characters.', '#language english',
          '#version 1',
          '; FlexCat reads a blank line as a message without an identifier, so',
          '; entries are separated by comment lines only.']
    header = ['/* Generated by tools/generate_catalog.py - do not edit. */',
              '#ifndef ND_STRINGS_H', '#define ND_STRINGS_H',
              'static const struct { long id; const char *text; } nd_strings[] = {']
    # Keep existing catalog IDs stable so translations survive new messages;
    # new strings get fresh IDs and removed strings simply disappear.
    previous = {}
    cd_path = ROOT / 'catalogs' / 'novadock.cd'
    if cd_path.exists():
        for ident, text in re.findall(r'^MSG_\d{4} \((\d+)//\)\n(.*)$',
                                      cd_path.read_text(), re.M):
            previous[text] = int(ident)
    next_id = max(previous.values(), default=0) + 1
    numbered = []
    for s in strings:
        if s in previous:
            numbered.append((previous[s], s))
        else:
            numbered.append((next_id, s))
            next_id += 1
    for n, s in sorted(numbered):
        cd += [';', 'MSG_%04d (%d//)' % (n, n), s]
        header.append('    {%d, "%s"},' % (n, s))
    header += ['};', '#endif', '']
    outputs = {ROOT / 'catalogs' / 'novadock.cd': '\n'.join(cd) + '\n',
               ROOT / 'include' / 'nd_strings.h': '\n'.join(header)}
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items()
                 if not p.exists() or p.read_text() != text]
        for ct in sorted((ROOT / 'catalogs').glob('*.ct')):
            ids = set(re.findall(r'^(MSG_\d{4})$', ct.read_text(encoding='latin-1'), re.M))
            wanted = set(re.findall(r'^(MSG_\d{4}) ', outputs[ROOT / 'catalogs' / 'novadock.cd'], re.M))
            if ids != wanted:
                stale.append(str(ct.relative_to(ROOT)) + ' (missing translations)')
        if stale:
            raise SystemExit('Catalog files out of date: ' + ', '.join(stale) +
                             '\nRun python3 tools/generate_catalog.py')
        print('Dock message catalog is current (%d strings).' % len(strings))
        return
    (ROOT / 'catalogs').mkdir(exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text)
    # Keep translation IDs in lockstep with the descriptor.  Preserve every
    # existing translation, drop retired IDs, and add a readable fallback for
    # a newly discovered string until a native translation is supplied.
    for ct_path in sorted((ROOT / 'catalogs').glob('*.ct')):
        old = ct_path.read_text(encoding='latin-1')
        first = re.search(r'^MSG_\d{4}\s*$', old, re.M)
        prefix = old[:first.start()].rstrip() if first else old.rstrip()
        prefix = '\n'.join(l for l in prefix.split('\n') if l.strip())
        translations = {}
        for match in re.finditer(
                r'^MSG_(\d{4})\n([^\n]*)\n; ([^\n]*)\s*$', old, re.M):
            translations[int(match.group(1))] = match.group(2)
        rebuilt = [prefix]
        # A new message starts in English; only Swedish has ready defaults.
        defaults = SV_DEFAULTS if ct_path.stem == 'svenska' else {}
        for ident, english in sorted(numbered):
            translated = translations.get(ident, defaults.get(english, english))
            # No blank lines: FlexCat reads one as a message without an ID.
            rebuilt += ['MSG_%04d' % ident, translated, '; ' + english]
        ct_path.write_text('\n'.join(rebuilt).rstrip() + '\n', encoding='latin-1')
    print('%d translatable dock messages' % len(strings))


if __name__ == '__main__':
    main()
