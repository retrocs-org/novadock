#!/usr/bin/env python3
"""Generate a deterministic source build ID; never uses wall time or Git state."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
HEADER='include/nd_build_id.h'
def inputs(root=ROOT):
    result={}
    for directory in ('src','prefs','include','plugin_src','tools','catalogs','Plugins','Icons','Themes','Backgrounds','Music'):
        for path in (root/directory).rglob('*'):
            name=path.relative_to(root).as_posix()
            if not path.is_file() or name==HEADER or any(x.startswith('.') or x=='__pycache__' for x in path.relative_to(root).parts):continue
            suffix=path.suffix.lower()
            code=directory in ('src','prefs','include','plugin_src') and suffix in ('.c','.h','.asm')
            helper=directory=='tools' and (suffix=='.c' or name=='tools/build_identity.py')
            catalog=directory=='catalogs' and suffix in ('.ct','.cd')
            asset=directory in ('Plugins','Icons','Themes','Backgrounds','Music') and suffix in ('.ndplugin','.ndart','.iff','.cfg','.info','.mod')
            if code or helper or catalog or asset:result[name]=hashlib.sha256(path.read_bytes()).hexdigest()
    for name in ('VERSION','Makefile','Makefile.cross','build.amiga','Install','install.amiga','novadock.cfg','scripts/build-amiga.sh','scripts/compile-amiga.py'):
        if (root/name).is_file():result[name]=hashlib.sha256((root/name).read_bytes()).hexdigest()
    return result
def identity(root=ROOT):
    version=next(line.split('=',1)[1].strip() for line in (root/'VERSION').read_text().splitlines() if line.startswith('VERSION='))
    digest=hashlib.sha256(json.dumps(inputs(root),sort_keys=True,separators=(',',':')).encode()).hexdigest()
    return version,digest
def header_text(root=ROOT):
    version,digest=identity(root)
    return ('#ifndef ND_BUILD_ID_H\n#define ND_BUILD_ID_H\n'
            '/* Generated by tools/build_identity.py from runtime source/assets. */\n'
            '#define ND_BUILD_SHORT "'+digest[:12]+'"\n'
            '#define ND_BUILD_ID "'+version+'-'+digest[:12]+'"\n'
            '#define ND_BUILD_SOURCE_SHA256 "'+digest+'"\n#endif\n')
def sync(check=False,root=ROOT):
    wanted=header_text(root);path=root/HEADER
    if not path.is_file() or path.read_text()!=wanted:
        if check:raise ValueError('Build ID is stale; run python3 tools/build_identity.py before building.')
        path.write_text(wanted)
    return identity(root)
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    try:version,digest=sync(a.check)
    except (OSError,ValueError) as error:p.exit(1,str(error)+'\n')
    print('NovaDock source build '+version+'-'+digest[:12])
if __name__=='__main__':main()
